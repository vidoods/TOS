#!/bin/bash
# ==============================================================================
# Умный скрипт для автоматической компиляции SCSS -> CSS
# ==============================================================================

SOURCE_FILE="assets/scss/style.scss"
DEST_FILE="assets/style.css"

echo "🔍 Проверка рабочего окружения..."

# 1. Проверка наличия установленного пакета sass
if ! command -v sass &> /dev/null; then
    echo "❌ Ошибка: Компилятор 'sass' не установлен в системе."
    echo "🔧 Решение: Установи его (потребуется Node.js), выполнив в терминале команду:"
    echo "   npm install -g sass"
    exit 1
fi

# 2. Проверка существования исходного файла SCSS
if [ ! -f "$SOURCE_FILE" ]; then
    echo "❌ Ошибка: Исходный файл '$SOURCE_FILE' не найден."
    echo "📁 Решение: Убедись, что папки assets/scss созданы, файл style.scss существует,"
    echo "   и ты запускаешь этот скрипт из КОРНЕВОЙ папки проекта."
    exit 1
fi

# 3. Успешный запуск
echo "✅ Sass установлен. Исходные файлы найдены."
echo "👓 Запускаем отслеживание изменений (Watch mode)..."
echo "   Нажми Ctrl+C для остановки."
echo "---------------------------------------------------"

# Запуск sass с флагом --watch
sass --watch "$SOURCE_FILE":"$DEST_FILE"